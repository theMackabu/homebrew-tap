#!/usr/bin/env python3
import hashlib
import json
import re
import subprocess
import tempfile
from pathlib import Path
from urllib.parse import parse_qs, urlsplit

ROOT = Path(__file__).resolve().parents[1]
MANIFEST = "https://manifest.antjs.org/v1/latest"
CHANNELS = {"stable": "ant", "canary": "ant-nightly"}
TARGETS = ("darwin-aarch64", "darwin-x64", "linux-aarch64", "linux-x64")
CURL = ["curl", "--fail", "--silent", "--show-error", "--location",
        "--retry", "3", "--connect-timeout", "30", "--max-time", "300"]


def fetch_manifest(channel):
    return json.loads(subprocess.check_output([*CURL, f"{MANIFEST}?channel={channel}"]))


def brew_version(entry):
    # Ant uses major.minor.git-hash.patch; hashes do not sort chronologically.
    match = re.fullmatch(r"(\d+)\.(\d+)\.([0-9a-f]{8,40})\.(\d+)", entry["version"])
    timestamp = entry["build_timestamp"]
    if not match or type(timestamp) is not int or timestamp <= 0:
        raise ValueError("Invalid Ant version or build timestamp")
    major, minor, _, patch = match.groups()
    return f"{major}.{minor}.{patch}.{timestamp}"


def select_entries(manifest, channel):
    if manifest.get("schema") != 1 or manifest.get("channel") != channel:
        raise ValueError(f"Unexpected manifest schema or channel for {channel}")
    entries = {}
    for entry in manifest["ant"]:
        target = entry["target"]
        if target not in TARGETS:
            continue
        if target in entries or entry.get("available") is not True:
            raise ValueError(f"Duplicate or unavailable target: {target}")
        url = entry["download_url"]
        parsed = urlsplit(url)
        query = parse_qs(parsed.query)
        if (parsed.scheme != "https" or parsed.netloc != "manifest.antjs.org"
                or parsed.path != f"/v1/download/ant/{target}"
                or not re.fullmatch(r"[1-9]\d*", query.get("run_id", [""])[0])
                or len(query["run_id"]) != 1 or parsed.fragment
                or any(c in url for c in ('"', "\\", "#", "\n", "\r"))):
            raise ValueError(f"Expected a run-pinned manifest download URL for {target}")
        if entry.get("filename") != "ant":
            raise ValueError(f"Expected an ant binary for {target}")
        if not re.fullmatch(r"[0-9a-f]{40}", entry["revision"]):
            raise ValueError(f"Invalid revision for {target}")
        brew_version(entry)
        entries[target] = {key: entry[key] for key in
                           ("version", "build_timestamp", "revision", "download_url")}
    if set(entries) != set(TARGETS):
        raise ValueError(f"Incomplete {channel} build; all four Homebrew targets are required")
    builds = {(entry["version"], entry["build_timestamp"], entry["revision"])
              for entry in entries.values()}
    if len(builds) != 1:
        raise ValueError(f"Mixed {channel} builds; waiting for a complete build")
    return entries


def download_sha256(url, target):
    with tempfile.TemporaryDirectory() as directory:
        binary = Path(directory) / "ant"
        subprocess.run([*CURL, "--output", str(binary), url], check=True)
        with binary.open("rb") as stream:
            magic = stream.read(4)
            expected = b"\xcf\xfa\xed\xfe" if target.startswith("darwin-") else b"\x7fELF"
            if magic != expected:
                raise ValueError(f"Download is not a {target} executable")
            stream.seek(0)
            return hashlib.file_digest(stream, "sha256").hexdigest()


def lock_entries(entries, previous):
    locked = {}
    for target in TARGETS:
        entry = entries[target]
        old = previous.get(target, {})
        checksum = old.get("sha256", "")
        if (any(old.get(key) != value for key, value in entry.items())
                or not re.fullmatch(r"[0-9a-f]{64}", checksum)):
            print(f"Hashing {target} ({entry['version']})", flush=True)
            checksum = download_sha256(entry["download_url"], target)
        locked[target] = {**entry, "sha256": checksum}
    return locked


def render_formula(channel, entries):
    nightly = channel == "canary"
    class_name = "AntNightly" if nightly else "Ant"
    other = "ant" if nightly else "ant-nightly"
    entry = entries[TARGETS[0]]
    desc = "Lightweight JavaScript runtime" + (" (nightly)" if nightly else "")
    lines = [
        "# Generated by scripts/update.py; do not edit by hand.",
        f"# Upstream version: {entry['version']} ({channel})",
        f"class {class_name} < Formula",
        f'  desc "{desc}"',
        '  homepage "https://antjs.org"',
        f'  version "{brew_version(entry)}"',
        '  license "MIT"',
        "",
        "  livecheck do",
        '    skip "Updated from manifest.antjs.org by the tap workflow"',
        "  end",
        "",
    ]
    for os_name, prefix in (("macos", "darwin"), ("linux", "linux")):
        lines.append(f"  on_{os_name} do")
        if os_name == "macos":
            lines += ['    depends_on macos: :sequoia', ""]
        for arch, target_arch in (("arm", "aarch64"), ("intel", "x64")):
            target = entries[f"{prefix}-{target_arch}"]
            lines += [
                f"    on_{arch} do",
                f'      url "{target["download_url"]}",',
                '          using:  :nounzip,',
                '          rename: "ant"',
                f'      sha256 "{target["sha256"]}"',
                "    end",
                "",
            ]
        lines[-1] = "  end"
        lines.append("")
    if nightly:
        lines.append('  conflicts_with "ant", because: "both install an ant executable"')
    lines += [
        f'  conflicts_with "themackabu/tap/{other}", because: "both install an ant executable"',
        "",
        "  def install",
        '    bin.install "ant"',
        "  end",
        "",
        "  test do",
        '    ENV["ANT_NO_VERSION_CHECK"] = "1"',
        f'    assert_match "{entry["version"]}", shell_output("#{{bin}}/ant --version")',
        '    (testpath/"hello.js").write \'console.log("hello from ant");\'',
        '    assert_equal "hello from ant\\n", shell_output("#{bin}/ant hello.js")',
        "  end",
        "end",
        "",
    ]
    return "\n".join(lines)


def update(root=ROOT):
    lock_path = root / "manifest-lock.json"
    previous = json.loads(lock_path.read_text()) if lock_path.exists() else {}
    locked = {}
    rendered = {}
    # Validate and download both channels before changing any tracked files.
    for channel, name in CHANNELS.items():
        entries = select_entries(fetch_manifest(channel), channel)
        locked[channel] = lock_entries(entries, previous.get(channel, {}))
        rendered[name] = render_formula(channel, locked[channel])
    (root / "Formula").mkdir(exist_ok=True)
    for name, content in rendered.items():
        (root / "Formula" / f"{name}.rb").write_text(content)
        print(f"Updated {name}")
    lock_path.write_text(json.dumps(locked, indent=2) + "\n")


if __name__ == "__main__":
    update()
